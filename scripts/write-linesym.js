const fs = require('fs');
const L = [];
L.push('"use client";');
L.push('import { useState, useEffect } from "react";');
L.push('import { sym, asset, hasGame } from "@/src/kb3/registry";');
L.push('');
L.push('function slugFromUrl(): string {');
L.push('  if (typeof window === "undefined") return "";');
L.push('  const m = window.location.pathname.match(/\\/casino\\/[a-z0-9]+\\/([a-z0-9-]+)/);');
L.push('  return m && m[1] ? m[1] : "";');
L.push('}');
L.push('');
L.push('export function LineSym({ k, set, size = 56 }: { k: number; set: string; size?: number }) {');
L.push('  const [slug, setSlug] = useState("");');
L.push('  const [failed, setFailed] = useState(false);');
L.push('  useEffect(function () { setSlug(slugFromUrl()); }, []);');
L.push('  const src = slug && hasGame(slug) ? sym(slug, k) : "";');
L.push('  if (src && !failed) {');
L.push('    return <img src={src} width={size} height={size} alt="" draggable={false} onError={function () { setFailed(true); }} style={{ objectFit: "contain", filter: "drop-shadow(0 2px 5px rgba(0,0,0,.55))" }}/>;');
L.push('  }');
L.push('  const hues = ["#ef3b52", "#f0b429", "#3fcf5f", "#9b5cf6", "#ff7a3d", "#17c9a4", "#ff4fa3", "#2fb6e8", "#ffd24a"];');
L.push('  const c = hues[((k % 9) + 9) % 9];');
L.push('  return (');
L.push('    <svg width={size} height={size} viewBox="0 0 64 64">');
L.push('      <circle cx="32" cy="32" r="24" fill={c} stroke="#1a1408" strokeWidth="2"/>');
L.push('      <circle cx="24" cy="24" r="7" fill="#ffffff" opacity="0.35"/>');
L.push('    </svg>');
L.push('  );');
L.push('}');
L.push('');
L.push('export function LineMascot({ hue, hue2, size = 200, slug }: { hue: string; hue2?: string; size?: number; slug?: string }) {');
L.push('  const [id, setId] = useState("");');
L.push('  const [failed, setFailed] = useState(false);');
L.push('  useEffect(function () { setId(slug || slugFromUrl()); }, [slug]);');
L.push('  const src = id && hasGame(id) ? asset(id, "character") : "";');
L.push('  if (!src || failed) return null;');
L.push('  return <img src={src} alt="" width={size} height={size} draggable={false} onError={function () { setFailed(true); }} style={{ objectFit: "contain", filter: "drop-shadow(0 0 22px " + hue + "80)" }}/>;');
L.push('}');
fs.writeFileSync('components/kb2/slots/LineSym.tsx', L.join('\n') + '\n', 'utf8');
const t = fs.readFileSync('components/kb2/slots/LineSym.tsx', 'utf8');
console.log('braces balanced=' + ((t.match(/\{/g)||[]).length === (t.match(/\}/g)||[]).length));
console.log('has LineSym=' + t.includes('export function LineSym'));
