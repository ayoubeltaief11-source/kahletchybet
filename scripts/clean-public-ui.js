const fs = require("fs");
let n = 0;
function edit(p, fn) {
  if (!fs.existsSync(p)) { console.log("SKIP " + p); return; }
  const before = fs.readFileSync(p, "utf8");
  const after = fn(before);
  if (after !== before) { fs.writeFileSync(p, after, "utf8"); n++; console.log("FIXED " + p); }
}
