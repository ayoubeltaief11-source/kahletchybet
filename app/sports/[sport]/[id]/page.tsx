"use client";
import Link from "next/link";
import { useParams } from "next/navigation";
import { useEffect, useMemo, useState } from "react";
import { useApp } from "@/components/Shell";
import Icon from "@/components/Icon";
import BetSlip, { type Selection } from "@/components/BetSlip";

export default function FixturePage() {
  const { sport, id } = useParams<{ sport: string; id: string }>();
  const { lang } = useApp();
  const [f, setF] = useState<any>(null);
  const [sim, setSim] = useState(true);
  const [loading, setLoading] = useState(true);
  const [group, setGroup] = useState("All");
  const [sels, setSels] = useState<Selection[]>([]);

  useEffect(() => {
    fetch("/api/sports/fixture?id=" + encodeURIComponent(id), { cache: "no-store" })
      .then(r => r.json()).then(d => { if (d.ok) { setF(d.fixture); setSim(!!d.simulated); } setLoading(false); })
      .catch(() => setLoading(false));
  }, [id]);

  const groups = useMemo<string[]>(() => ["All", ...Array.from(new Set<string>((f?.markets ?? []).map((m: any) => String(m.group ?? "Main"))))], [f]);
  const markets = (f?.markets ?? []).filter((m: any) => group === "All" || m.group === group);
  const count = (f?.markets ?? []).reduce((a: number, m: any) => a + m.picks.length, 0);

  const toggle = (m: any, p: any) => {
    const key = `${f.id}|${m.key}|${p.label}`;
    setSels(prev => prev.some(s => s.key === key) ? prev.filter(s => s.key !== key)
      : [...prev.filter(s => !s.key.startsWith(`${f.id}|${m.key}|`)), { key, fixture: f.id, label: `${f.home} v ${f.away}`, market: m.name, pick: p.label, price: p.price }]);
  };
  const has = (m: any, p: any) => sels.some(s => s.key === `${f.id}|${m.key}|${p.label}`);

  if (loading) return <div className="col">{[0, 1, 2].map(i => <div key={i} className="skel" />)}</div>;
  if (!f) return <div className="empty"><Icon name="info" /><div>Fixture unavailable.</div><Link href={"/sports/" + sport} className="btn o s" style={{ marginTop: 14 }}>Back</Link></div>;

  return (
    <div className="split">
      <div className="col">
        <Link href={"/sports/" + sport} className="btn o s" style={{ alignSelf: "flex-start" }}>â† {sport}</Link>

        <div className="hero" style={{ padding: "26px 24px" }}>
          <div className="bt xxs" style={{ color: "var(--dim)" }}>
            <span>{f.league}</span>
            <span className="row" style={{ gap: 6 }}>{f.state === "LIVE" && <span className="dot" />}{f.state === "LIVE" ? (f.minute ? f.minute + "'" : "LIVE") : new Date(f.kickoff).toLocaleString()}</span>
          </div>
          <div className="teams" style={{ marginTop: 18 }}>
            <div className="tm" style={{ fontSize: 17 }}><div className="crest-sm" style={{ width: 42, height: 42, flex: "0 0 42px" }}>{f.homeLogo ? <img src={f.homeLogo} alt="" style={{ width: 30, height: 30 }} /> : <b>{f.home[0]}</b>}</div><span className="clip">{f.home}</span></div>
            <div className="score" style={{ fontSize: 24, padding: "10px 18px" }}>{f.scoreHome ?? "-"} : {f.scoreAway ?? "-"}</div>
            <div className="tm r" style={{ fontSize: 17 }}><div className="crest-sm" style={{ width: 42, height: 42, flex: "0 0 42px" }}>{f.awayLogo ? <img src={f.awayLogo} alt="" style={{ width: 30, height: 30 }} /> : <b>{f.away[0]}</b>}</div><span className="clip">{f.away}</span></div>
          </div>
          <div className="bt wrap mt">
            <span className={"tag " + (sim ? "v" : "j")}>{sim ? "SIMULATED MARKETS" : "PROVIDER + SIMULATED"}</span>
            <span className="tag g">{f.markets.length} markets - {count} selections</span>
          </div>
        </div>

        <div className="note v">Educational simulation. Odds are generated by a coherent probability model and are not real bookmaker prices. All stakes use virtual credits.</div>

        <div className="tabs">
          {groups.map((g: string) => <button key={g} className={"tab" + (group === g ? " on" : "")} onClick={() => setGroup(g)}>{g}</button>)}
        </div>

        {markets.map((m: any) => (
          <div key={m.key} className="card pad">
            <div className="bt mb"><h3 className="h3" style={{ margin: 0 }}>{m.name}</h3><span className="tag n">{m.picks.length}</span></div>
            <div className="odds" style={{ gridTemplateColumns: `repeat(${m.picks.length <= 3 ? m.picks.length : m.picks.length <= 4 ? 2 : 3},1fr)` }}>
              {m.picks.map((p: any) => (
                <button key={p.label} className={"odd" + (has(m, p) ? " on" : "")} onClick={() => toggle(m, p)}>
                  <i>{p.label}</i><b>{Number(p.price).toFixed(2)}</b>
                </button>
              ))}
            </div>
          </div>
        ))}
      </div>
      <BetSlip selections={sels} remove={k => setSels(p => p.filter(s => s.key !== k))} clear={() => setSels([])} />
    </div>
  );
}